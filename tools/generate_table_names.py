"""Reviewed BufferObjectTable TypeName owners, numeric/String and pointer tables."""
import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parents[1]
ROWS = [("int", "int", 1, 20, "4604c0"),
        ("String", "int", 1, 21, "461250"),
        ("String", "float", 2, 22, "461ec0"),
        ("String", "String", 3, 23, "462d40"),
        ("int", "String", 3, 24, "463930"),
        ("float", "String", 3, 25, "4644f0"),
        ("int", "Character *", None, 5, "465360"),
        ("int", "Creature *", None, 10, "466840")]


def main():
    source = ['// Generated by tools/generate_table_names.py; original shared-cache name builders.',
              '#define BUFFEROBJECT_SIGNATURES', '#include "String/String.h"',
              '#include "Container/ContainerTable.h"', '#include "Container2/ObjectArrayViews.h"',
              '#include <stdio.h>', '#include <string.h>',
              'extern const char *g_arrayBase; // 0x4bf958',
              'extern char *g_arrayName; // 0x4bf95c',
              'template <class K, class V, class A, int ID>',
              'const char *BufferObjectTable<K,V,A,ID>::TypeName() {',
              '    char *name = g_arrayName;',
              '    if (!name) {',
              '        name = new char[strlen(g_arrayBase) + 1];',
              '        strcpy(name, g_arrayBase);',
              '    }',
              '    g_arrayName = name;',
              '    sprintf(name + strlen("PrimArray"), "%2x", ID);',
              '    return g_arrayName;', '}', '']
    targets = []
    for key, value, aid, ident, address in ROWS:
        array = ('PrimitiveArray<%s,%d>' % (value, aid)) if aid else ('ObjArrayC' if ident == 5 else 'ObjArrayD')
        source.append('template const char *BufferObjectTable<%s,%s,%s,%d>::TypeName(); // 0x%s'
                      % (key, value, array, ident, address))
        # Match the ID suffix so String's abbreviation spelling is irrelevant.
        suffix = ('B' + chr(ord('A') + ident - 16) + '@@@') if ident >= 16 else (str(ident - 1) + '@@')
        targets.append(r'^\?TypeName@\?\$BufferObjectTable@.*\$0' + suffix
                       + r'UAEPBDXZ$ ' + address + ' table_name_%d 128' % ident)
    folder = REPO / 'src/Container2'
    (folder / 'TableNames.cpp').write_text('\n'.join(source) + '\n')
    (folder / 'targets_table_names.txt').write_text('\n'.join(targets) + '\n')


if __name__ == '__main__':
    main()
