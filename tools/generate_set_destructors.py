"""Materialize reviewed Set destructor specializations, not whole template classes.

Addresses come from Container/gen/targets_SetDtor.txt and its original type/ID
labels. Set<int,21> has no reviewed original identity and is deliberately absent.
"""
import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parents[1]
ROWS = [
    ("String", 11, "45f700", "BF"),
    ("int", 20, "46ed90", "BE"),
    ("String", 21, "46edf0", "BF"),
    ("String", 22, "46ee50", "BG"),
    ("String", 23, "46eeb0", "BH"),
    ("int", 24, "46ef10", "BI"),
    ("float", 25, "46ef70", "BJ"),
    ("int", 5, "46efd0", "4"),
    ("String", 0, "46f0b0", "A"),
    ("int", 9, "46f190", "8"),
    ("String", 50, "46f2f0", "DC"),
    ("String", 51, "46f370", "DD"),
]


def main():
    folder = REPO / "src/Container/gen"
    source = ['// Reviewed Set destructor owners; generated by tools/generate_set_destructors.py.',
              '#define CONTAINER_DEFINITIONS', '#define SET_DTOR',
              '#include "String/String.h"', '#include "Container/ContainerSet.h"', '']
    targets = []
    for typ, ident, address, code in ROWS:
        # VC4 encodes small integer template arguments as value-1 digits.
        if typ == "String" and ident == 11:
            code = "L"
        encoded = code + ("@@" if ident in (5, 9) else "@@@")
        type_code = {"String": "VString@@", "int": "H", "float": "M"}[typ]
        symbol = "??1?$Set@" + type_code + "$0" + encoded + "QAE@XZ"
        source.append("template Set<%s, %d>::~Set(); // 0x%s" % (typ, ident, address))
        targets.append("^" + re.escape(symbol) + "$ " + address + " set_dtor_%s_%d 92" % (typ.lower(), ident))
    (folder / "SetDtorOwners.cpp").write_text("\n".join(source) + "\n")
    (folder / "targets_SetDtorOwners.txt").write_text("\n".join(targets) + "\n")


if __name__ == "__main__":
    main()
