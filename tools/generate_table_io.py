"""Generate reviewed table stream owners from the original secondary vtables."""
import pathlib
from generate_table_names import ROWS, REPO


def main():
    rtti = [line.split('\t') for line in (REPO.parent / 'tools/rtti.tsv').read_text().splitlines()
            if line.startswith('.?AV?$BufferObjectTable@')]
    source = ['// Generated by tools/generate_table_io.py; key array then value array.',
              '#define BUFFEROBJECT_SIGNATURES', '#include "String/String.h"',
              '#include "Container/ContainerTable.h"', '#include "Container2/ObjectArrayViews.h"',
              'template <class K, class V, class A, int ID>',
              'void BufferObjectTable<K,V,A,ID>::Write(void *stream) {',
              '    ((BufferObject *)((char *)&keys + 0x10))->Write(stream);',
              '    ((BufferObject *)((char *)&values + 0x10))->Write(stream);', '}',
              'template <class K, class V, class A, int ID>',
              'void BufferObjectTable<K,V,A,ID>::Read(void *stream) {',
              '    ((BufferObject *)((char *)&keys + 0x10))->Read(stream);',
              '    ((BufferObject *)((char *)&values + 0x10))->Read(stream);', '}', '']
    targets = []
    for key, value, aid, ident, name_address in ROWS:
        matches = [r for r in rtti if r[2] == '44' and r[4].split(';')[0].lower() == '00' + name_address]
        if len(matches) != 1:
            raise ValueError('No unique reviewed vtable for table ID %d' % ident)
        slots = matches[0][4].split(';')
        array = ('PrimitiveArray<%s,%d>' % (value, aid)) if aid else ('ObjArrayC' if ident == 5 else 'ObjArrayD')
        suffix = ('B' + chr(ord('A') + ident - 16) + '@@@') if ident >= 16 else (str(ident - 1) + '@@')
        for method, slot in [('Write', 2), ('Read', 3)]:
            address = slots[slot].lstrip('0').lower()
            source.append('template void BufferObjectTable<%s,%s,%s,%d>::%s(void *); // 0x%s'
                          % (key, value, array, ident, method, address))
            targets.append(r'^\?' + method + r'@\?\$BufferObjectTable@.*\$0' + suffix
                           + r'UAEXPAX@Z$ ' + address + ' table_%s_%d 48' % (method.lower(), ident))
    folder = REPO / 'src/Container2'
    (folder / 'TableIO.cpp').write_text('\n'.join(source) + '\n')
    (folder / 'targets_table_io.txt').write_text('\n'.join(targets) + '\n')


if __name__ == '__main__':
    main()
