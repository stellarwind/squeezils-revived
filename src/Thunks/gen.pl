# Generates Thunks.cpp + targets.txt from candidate (addr size) pairs on stdin: 16-byte `mov ecx, imm; jmp rel` thunks.
my (@t, $src);
$src = "// Tail-calling accessor thunks: `mov ecx, &global; jmp Method` (generated by gen.pl; one object+method per thunk).\n";
while (<STDIN>) {
    my ($a, $s) = split; next unless $s == 16;
    my $end = sprintf("0x%x", hex($a) + 16);
    my $txt = join("", `objdump -d -M intel --start-address=0x$a --stop-address=$end Exported/SQZ.EXE`); $txt =~ s{}{}g;
    next unless $txt =~ /\tmov +ecx,0x([0-9a-f]+)\n.*\tjmp +0x([0-9a-f]+)/s;
    my ($g, $tg) = ($1, $2);
    $src .= "struct O$a { void M(); };   // M = 0x$tg\nextern O$a g_$a;           // 0x$g\nvoid Thunk$a() { g_$a.M(); }\n\n";
    push @t, "^\?Thunk$a\@\@  $a thunk$a\n";
}
open C, ">Repo/src/Thunks/Thunks.cpp"; print C $src; close C;
open T, ">Repo/src/Thunks/targets.txt"; print T @t; close T;
print scalar(@t), " thunks\n";
